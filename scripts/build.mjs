import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dist=path.join(root,'dist');
fs.rmSync(dist,{recursive:true,force:true});fs.mkdirSync(dist,{recursive:true});
for(const name of ['index.html','styles.css','app.js','firebase-client.js']) fs.copyFileSync(path.join(root,name),path.join(dist,name));
const publicDir=path.join(root,'public');
if(fs.existsSync(publicDir)) for(const name of fs.readdirSync(publicDir)) fs.copyFileSync(path.join(publicDir,name),path.join(dist,name));
console.log('BrandLens static client built to dist/.');
